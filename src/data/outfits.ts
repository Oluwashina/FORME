/* ---------- resolution ---------- */

const resolve = (r: RawOutfit, index: number): Outfit => {
  const d = WHY_DEFAULTS[r.aes]
  const aes = r.aes
  return {
    id: r.id,
    number: index + 1,
    title: r.title,
    summary: r.summary,
    aesthetic: aes,
    aestheticTags: [aes, ...(r.tags ?? [])],
    occasion: r.occ,
    occasions: r.occs ?? [r.occ],
    formality: r.f,
    moods: r.moods,
    clothingTypes: r.types,
    paletteFamilies: r.fams,
    image: {
      id: r.img[0],
      ratio: r.img[1],
      focus: r.img[2] ?? 'center 25%',
      alt: `${r.title} — a ${aes.replace('-', ' ')} outfit`,
    },
    palette: r.pal.map(([key, role]) => ({ ...color(key), role })),
    paletteRelation: r.rel,
    paletteNote: r.palNote,
    items: r.items.map((ref) => {
      const [key, note] = Array.isArray(ref) ? ref : [ref, undefined]
      const t = item(key)
      return { ...t, outfitNote: note ?? t.note }
    }),
    logic: r.logic,
    why: {
      silhouette: d.silhouette,
      proportions: r.prop ?? d.proportions,
      colorBalance: r.cb,
      formality: FORMALITY_WHY[r.f],
      accessories: r.acc ?? d.accessories,
    },
  }
}

export const OUTFITS: Outfit[] = raw.map(resolve)

export const OUTFIT_BY_ID: Record<string, Outfit> = Object.fromEntries(OUTFITS.map((o) => [o.id, o]))

export const getOutfit = (id: string) => OUTFIT_BY_ID[id]
